"""`greenthread report`: regenerate docs/TEST_REPORT.md from the files in results/.

Everything in the report is read from result files written by the other commands,
and each hypothesis verdict is computed by a stated rule, so running the pipeline on
a new machine and then `report` replaces every number without hand editing.
"""
from __future__ import annotations

import json
import math
import platform
import re
from datetime import datetime
from pathlib import Path

import pandas as pd

from .config import Config, PACKAGE_ROOT


def _read_text(p: Path) -> str:
    try:
        raw = p.read_bytes()
    except Exception:
        return ""
    for enc in ("utf-8-sig", "utf-8", "cp1252", "utf-16"):
        try:
            return raw.decode(enc)
        except (UnicodeDecodeError, LookupError):
            continue
    return raw.decode("utf-8", errors="replace")


def _j(p: Path):
    try:
        txt = _read_text(p)
        return json.loads(txt) if txt else None
    except Exception:
        return None


def _csv(p: Path):
    try:
        return pd.read_csv(p)
    except Exception:
        return None


def _f(x, nd=1, pct=False):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{100 * x:.{nd}f}" if pct else f"{x:.{nd}f}"


def _row(df, **kw):
    if df is None:
        return None
    m = pd.Series(True, index=df.index)
    for k, v in kw.items():
        m &= df[k].astype(str) == str(v)
    d = df[m]
    return d.iloc[0] if len(d) else None


def build(cfg: Config) -> str:
    R = cfg.resolve(cfg.results_dir)
    caps = _j(R / "capabilities.json") or {}
    c = caps.get("capabilities", {})
    pm = _j(R / "power_model.json")
    idle = _j(R / "idle_w.json") or {}
    met = _j(R / "model_metrics.json")
    td = _csv(R / "training_data.csv")
    sim = R / "simulation"
    e = {k: _csv(sim / f"{k}_summary.csv") for k in ("e1", "e2", "e3", "e4", "e5", "e6", "e7", "tune")}
    meta = _j(sim / "meta.json") or {}
    led = _csv(R / "ledger" / "ledger_study.csv")
    led_field = _j(R / "ledger_report.json")
    clog = _csv(cfg.resolve(cfg.carbon.log_path))
    sig_state = _j(cfg.resolve(cfg.carbon.signal_state_path))
    pyt = _read_text(R / "pytest_output.txt") if (R / "pytest_output.txt").exists() else ""
    exps = sorted(R.glob("experiment_*/summary.md"))
    L: list[str] = []
    A = L.append

    A("# GreenThread — Test and Results Report")
    A("")
    A(f"_Generated by `python -m greenthread report` on {datetime.now():%d %b %Y %H:%M} from the files in "
      f"`results/`. Re-run the pipeline on another machine and then `report` to replace every number._")
    A("")
    A(f"_Clock: {datetime.now().astimezone():%Z (UTC%z)} on the machine that generated it._")
    A("")
    # ---------------------------------------------------------------- 1
    A("## 1. Machine and measurement setup")
    A("")
    if c:
        A("| Item | Value |")
        A("|---|---|")
        A(f"| OS / backend | {c.get('os_name')} {c.get('os_build','')} / `{caps.get('backend')}` |")
        A(f"| CPU | {c.get('cpu_model')} — {c.get('physical_cores')} cores / {c.get('logical_cpus')} threads, "
          f"hybrid: {c.get('heterogeneous')} |")
        A(f"| Supported modes | {', '.join(caps.get('supported_modes', []))} |")
        A(f"| Frequency-lowering ECO (EcoQoS / util-clamp) | {c.get('ecoqos')} |")
        A(f"| Battery / energy counter | {c.get('battery_present')} / {c.get('battery_energy_counter')} |")
        A(f"| Energy meter | {c.get('power_meter')}{' + RAPL' if caps.get('energy_meter') else ''} |")
        if idle:
            A(f"| Idle power | device (battery) {_f(idle.get('idle_w'), 2)} W, package (RAPL) {_f(idle.get('rapl_idle_w'), 2)} W |")
        if pm:
            A(f"| Power model ({pm.get('source','config default')}) | idle {pm['idle_w']:.2f} W, "
              f"{pm['per_core_w_normal']:.2f} W/core normal, {pm['per_core_w_eco']:.2f} W/core ECO |")
        else:
            A("| Power model | **config defaults (not calibrated on this machine)** |")
        for n in c.get("notes", []):
            A(f"| Note | {n} |")
        probe = caps.get("probe")
        if probe:
            bad = {k: v["failures"] for k, v in probe.items() if isinstance(v, dict) and v.get("failures")}
            A(f"| Control probe | {'all controls applied' if not bad else 'failures: ' + json.dumps(bad)} |")
    else:
        A("_No `results/capabilities.json` — run `python -m greenthread detect --probe`._")
    A("")
    # ---------------------------------------------------------------- 2
    A("## 2. Automated tests")
    A("")
    m = re.search(r"(\d+) passed(?:, (\d+) failed)?(?:, (\d+) skipped)?", pyt)
    if m:
        A(f"`pytest`: **{m.group(1)} passed**, {m.group(2) or 0} failed, {m.group(3) or 0} skipped "
          f"(`results/pytest_output.txt`).")
    else:
        A("_Run `python -m pytest -q | tee results/pytest_output.txt`._")
    A("")
    # ---------------------------------------------------------------- 3
    A("## 3. Prediction layer (real runs on this machine)")
    A("")
    if met:
        ts, us = met["temporal_split"], met["unseen_size_split"]
        n_meas = int(td.energy_wh_measured.notna().sum()) if td is not None and "energy_wh_measured" in td else 0
        A(f"{met['n_samples']} runs; {n_meas} with measured energy. Run-to-run noise (identical repeated runs): "
          f"{_f(ts['label_noise']['runtime_log_sd'], 3)} log-sd ({ts['label_noise']['replicate_groups']} groups).")
        A("")
        A("| Split | Predictor | MAPE % | q0.9 coverage | Pinball q0.9 | model error (noise removed) |")
        A("|---|---|---|---|---|---|")
        for name, sp in (("temporal 60/20/20", ts), ("unseen largest size", us)):
            for k in ("ml", "table"):
                r = sp[k]
                A(f"| {name} | {'ML (GBDT quantile)' if k == 'ml' else 'table baseline'} | {_f(r['mape_pct'])} | "
                  f"{_f(r['coverage_q90'], 3)} | {_f(r['pinball_q90'], 3)} | {_f(r.get('model_log_err_sd'), 3)} |")
        mc = ts.get("mode_comparison", {})
        if mc:
            nr = mc.get("cpu_ratio_model_error_noise_removed", {})
            A("")
            A(f"Mode comparison (error of predicted energy/CPU ratio mode÷NORMAL, noise removed, n = {mc['n']}): "
              f"ML direct {_f(nr.get('ml_direct_difference'), 3)}, ML paired-ratio model {_f(nr.get('ml_paired'), 3)} "
              f"(not used: worse), table {_f(nr.get('table'), 3)}.")
        A("")
        A(f"Inference {_f(met['ml_inference_ms'], 1)} ms per decision (all modes), model {_f(met['model_size_kb'], 0)} KB.")
    else:
        A("_Run `collect` and `train`._")
    A("")
    # ---------------------------------------------------------------- 4
    A("## 4. Real-process experiments on this machine")
    A("")
    if exps:
        desc = {"ac": "plugged in, compressed real carbon trace", "battery": "on battery",
                "tight": "tight deadlines, escalation disabled", "linux_testbed": "Linux testbed"}
        for p in exps:
            tag = p.parent.name.replace("experiment_", "")
            extra = (" — ECO energy saving ASSUMED (default power model), timing real"
                     if "assumed" in tag else "")
            A(f"### `{tag}` — {desc.get(tag.split('_')[0], tag)}{extra}")
            A("")
            A(_read_text(p).strip())
            A("")
    else:
        A("_Run `experiment` (see `scripts/run_all_*`)._")
        A("")
    # ---------------------------------------------------------------- 5
    A("## 5. Trace-driven simulation")
    A("")
    if e["e1"] is not None:
        P = meta.get("predictor_errors", {})
        A(f"Windows: {meta.get('windows','')}. Seeds per trace: {meta.get('seeds')}. Predictor errors from "
          f"`{P.get('source')}`. Machine model: {json.dumps({k: v for k, v in meta.get('machine', {}).items() if k != 'modes'})}. "
          f"Full tables: `results/simulation/SIMULATION_RESULTS.md`.")
        A("")
        A("**E1 carbon saving vs default on AC (95 % CI)**")
        A("")
        A("| trace | carbon_only | combined_noai | greenthread | greenthread miss % |")
        A("|---|---|---|---|---|")
        for tr in e["e1"].trace.unique():
            g = lambda p: _row(e["e1"], trace=tr, policy=p)
            fm = lambda r: "n/a" if r is None else f"{r.carbon_saving_pct:.1f} ± {r.carbon_saving_pct_ci95:.1f}"
            gt = g("greenthread")
            A(f"| {tr} | {fm(g('carbon_only'))} | {fm(g('combined_noai'))} | {fm(gt)} | {_f(gt.miss_rate, 2, True) if gt is not None else 'n/a'} |")
        A("")
        if e["e3"] is not None:
            A("**E3 carbon-signal quality** (carbon saving %, AC)")
            A("")
            A("| forecast | noise | outage | shift h | no uncertainty | fixed decay (v1) | adaptive (GreenThread) |")
            A("|---|---|---|---|---|---|---|")
            for _, k in e["e3"][["forecast_kind", "forecast_noise", "outage_frac", "forecast_shift_h"]].drop_duplicates().iterrows():
                kk = dict(k)
                v = lambda p: _row(e["e3"], policy=p, **kk)
                fm = lambda r: "n/a" if r is None else f"{r.carbon_saving_pct:.1f} ± {r.carbon_saving_pct_ci95:.1f}"
                A(f"| {kk['forecast_kind']} | {kk['forecast_noise']} | {kk['outage_frac']} | {kk['forecast_shift_h']} | "
                  f"{fm(v('gt_no_uncertainty'))} | {fm(v('gt_fixed_conf'))} | {fm(v('greenthread'))} |")
            A("")
        if e["e4"] is not None:
            A("**E4 battery energy saving vs default**")
            A("")
            A("| SoC | always-ECO heuristic | GreenThread v1 | GreenThread | GreenThread p95 slowdown |")
            A("|---|---|---|---|---|")
            for soc in sorted(e["e4"].soc.astype(str).unique()):
                v = lambda p: _row(e["e4"], policy=p, soc=soc)
                fm = lambda r: "n/a" if r is None else f"{r.energy_saving_pct:.1f} ± {r.energy_saving_pct_ci95:.1f}"
                gt = v("greenthread")
                A(f"| {soc} | {fm(v('heuristic'))} | {fm(v('greenthread_v1'))} | {fm(gt)} | {_f(gt.p95_slowdown, 2) if gt is not None else 'n/a'} |")
            A("")
        if e["e5"] is not None:
            A("**E5 tight deadlines** (miss rate %, energy saving %)")
            A("")
            A("| power | escalation | always-ECO | median check | quantile check (GreenThread) |")
            A("|---|---|---|---|---|")
            for _, k in e["e5"][["on_ac", "escalate"]].drop_duplicates().iterrows():
                v = lambda p: _row(e["e5"], policy=p, on_ac=k.on_ac, escalate=k.escalate)
                fm = lambda r: "n/a" if r is None else f"{100 * r.miss_rate:.2f} miss / {r.energy_saving_pct:.1f} saved"
                A(f"| {'AC' if k.on_ac == True or str(k.on_ac) == 'True' else 'battery'} | {k.escalate} | "
                  f"{fm(v('heuristic'))} | {fm(v('gt_no_quantile'))} | {fm(v('greenthread'))} |")
            A("")
        if e["e6"] is not None:
            A("**E6 robust mode selection vs mode-effect prediction error** (battery energy saving %)")
            A("")
            A("| mode-effect error | always-ECO | no shrinkage/gate | GreenThread |")
            A("|---|---|---|---|")
            for sg in sorted(e["e6"].sigma_rel_ml.astype(float).unique()):
                v = lambda p: _row(e["e6"], policy=p, sigma_rel_ml=sg)
                fm = lambda r: "n/a" if r is None else f"{r.energy_saving_pct:.1f} ± {r.energy_saving_pct_ci95:.1f}"
                A(f"| {sg} | {fm(v('heuristic'))} | {fm(v('gt_no_gate'))} | {fm(v('greenthread'))} |")
            A("")
    else:
        A("_Run `simulate`._")
        A("")
    # ---------------------------------------------------------------- 6
    A("## 6. Battery carbon ledger")
    A("")
    if led is not None:
        A("Year-long simulation over real traces (`results/ledger/LEDGER_STUDY.md`): error of counting battery "
          "energy at the grid intensity *when used* instead of *when charged* (zero-accounting error is always −100 %).")
        A("")
        A("| trace | " + " | ".join(dict.fromkeys(led.profile)) + " |")
        A("|---|" + "---|" * led.profile.nunique())
        for tr in dict.fromkeys(led.trace):
            d = led[led.trace == tr].set_index("profile")
            A(f"| {tr} | " + " | ".join(f"{d.loc[p, 'tou_error_pct']:+.1f} %" for p in dict.fromkeys(led.profile)) + " |")
        A("")
    if led_field:
        cg = led_field["carbon_g"]
        A(f"**Field log on this laptop** ({_f(led_field['hours_logged'])} h, {_f(led_field['battery_energy_used_wh'])} Wh "
          f"drawn from the battery): ledger {cg['ledger']:.2f} g, time-of-use {cg['time_of_use']:.2f} g "
          f"({_f(led_field.get('time_of_use_error_pct'))} % error), zero 0 g. Mean grid intensity while charging "
          f"{_f(led_field.get('mean_grid_intensity_while_charging'), 0)} vs while discharging "
          f"{_f(led_field.get('mean_grid_intensity_while_discharging'), 0)} gCO2e/kWh.")
    else:
        A("_Field log: run `ledger-track` for a few days of normal use, then `ledger-report`._")
    A("")
    # ---------------------------------------------------------------- 7
    A("## 7. Live grid data")
    A("")
    if clog is not None and len(clog):
        A(f"`{cfg.carbon.log_path}`: {len(clog)} hourly values for zone {clog.zone.iloc[0]} from "
          f"{clog.timestamp.min()} to {clog.timestamp.max()}; mean {clog.carbon_intensity.mean():.0f}, "
          f"min {clog.carbon_intensity.min():.0f}, max {clog.carbon_intensity.max():.0f} gCO2e/kWh. "
          f"Replay it with `csv_path = \"{cfg.carbon.log_path}\"`.")
    else:
        A("_No live log yet: with a token, run `carbon-log --config configs/india_live.toml`._")
    if sig_state:
        A(f"Adaptive signal state: {int(sum(sig_state['n']))} forecasts scored against observed values.")
    A("")
    # ---------------------------------------------------------------- 8
    A("## 8. Hypotheses — verdicts (computed by the stated rules)")
    A("")
    A("| Hypothesis | Rule | Verdict | Evidence |")
    A("|---|---|---|---|")
    for h in _verdicts(e, met, led, pm, td, exps):
        A(f"| {h[0]} | {h[1]} | **{h[2]}** | {h[3]} |")
    A("")
    # ---------------------------------------------------------------- 9
    arch = sorted((R / "archive").glob("*/model_metrics.json"))
    if arch:
        A("## 9. Other machines (archived)")
        A("")
        A("| machine | runs | ML MAPE % | table MAPE % |")
        A("|---|---|---|---|")
        for p in arch:
            m2 = _j(p)
            if m2:
                A(f"| {p.parent.name} | {m2['n_samples']} | {_f(m2['temporal_split']['ml']['mape_pct'])} | "
                  f"{_f(m2['temporal_split']['table']['mape_pct'])} |")
        xm = _j(R / "cross_machine.json")
        if xm:
            A("")
            A(f"Model trained on `{xm['train']}` and applied to this machine without retraining: MAPE "
              f"{_f(xm['ml_mape_pct'])} % (vs {_f(xm['own_ml_mape_pct'])} % when trained here) — models must be "
              f"trained on the machine they schedule.")
        A("")
    return "\n".join(L) + "\n"


def _real(exps, prefix):
    """Per-policy summary rows of the first real experiment whose tag starts with prefix."""
    for p in exps:
        if p.parent.name.replace("experiment_", "").startswith(prefix):
            s = _csv(p.parent / "summary.csv")
            if s is not None:
                return s.set_index("policy"), p.parent.name.replace("experiment_", "")
    return None, None


def _verdicts(e, met, led, pm, td, exps):
    out = []
    real_ac, tag_ac = _real(exps, "ac")
    real_tight, tag_tight = _real(exps, "tight")
    e1, e2, e3, e4, e5, e6 = (e[k] for k in ("e1", "e2", "e3", "e4", "e5", "e6"))
    # H1
    if e1 is not None:
        gt = e1[e1.policy == "greenthread"]
        de = e1[e1.policy == "default"]
        lows = gt.carbon_saving_pct - gt.carbon_saving_pct_ci95
        ok = (lows > 0).all() and (gt.miss_rate.max() <= de.miss_rate.max() + 0.005)
        out.append(("H1 carbon reduction on AC without extra misses", "CI lower bound > 0 on every trace, miss rate ≤ default + 0.5 pt",
                    "Supported (simulation)" if ok else "Not supported",
                    f"savings {gt.carbon_saving_pct.min():.1f}–{gt.carbon_saving_pct.max():.1f} %, max miss {100*gt.miss_rate.max():.2f} %"
                    + (f"; real `{tag_ac}`: {real_ac.loc['greenthread','carbon_saving_pct']:.1f} ± "
                       f"{real_ac.loc['greenthread','carbon_saving_pct_ci95']:.1f} %, misses {real_ac.loc['greenthread','misses']:.2f}/run"
                       if real_ac is not None and "greenthread" in real_ac.index else "")))
    # H2
    if e5 is not None:
        ne = e5[e5.escalate.astype(str) == "False"]
        q = ne[ne.policy == "greenthread"].miss_rate.mean()
        md = ne[ne.policy == "gt_no_quantile"].miss_rate.mean()
        h = ne[ne.policy == "heuristic"].miss_rate.mean()
        out.append(("H2 quantile check prevents misses a median check causes", "tight deadlines, no escalation: quantile misses < median misses",
                    "Supported (simulation)" if q < md else "Not supported",
                    f"miss rate quantile {100*q:.2f} % vs median {100*md:.2f} % vs always-ECO {100*h:.2f} %"
                    + (f"; real `{tag_tight}`: misses/run {real_tight.loc['greenthread','misses']:.2f} (quantile) vs "
                       f"{real_tight.loc['gt_no_quantile','misses']:.2f} (median)"
                       if real_tight is not None and {"greenthread", "gt_no_quantile"} <= set(real_tight.index) else "")))
    # H3
    if e3 is not None:
        d = e3.copy()
        d["key"] = d.forecast_kind.astype(str) + "/" + d.forecast_noise.astype(str) + "/" + d.outage_frac.astype(str) + "/" + d.forecast_shift_h.astype(str)
        p = d.pivot_table(index="key", columns="policy", values="carbon_saving_pct")
        diff = p["greenthread"] - p["gt_no_uncertainty"]
        mis = [k for k in diff.index if not k.endswith("/0.0")]
        never_loses = (diff >= -0.5).all()
        wins = (diff[mis] >= 1.0).all() if mis else False
        out.append(("H3 uncertainty handling never hurts and helps under misleading signals",
                    "adaptive ≥ unaware − 0.5 pt in every case; ≥ +1 pt with shifted forecasts",
                    "Supported (simulation)" if never_loses and wins else ("Partly" if never_loses or wins else "Not supported"),
                    f"worst case {diff.min():+.1f} pt, misleading-forecast gain {diff[mis].min():+.1f}…{diff[mis].max():+.1f} pt" if mis else f"worst {diff.min():+.1f} pt"))
    # H4
    if met is not None and e2 is not None:
        ml, tb = met["temporal_split"]["ml"]["mape_pct"], met["temporal_split"]["table"]["mape_pct"]
        g = _row(e2, policy="greenthread"); n = _row(e2, policy="gt_no_ml")
        ok = ml < tb and g is not None and n is not None and g.carbon_saving_pct >= n.carbon_saving_pct
        out.append(("H4 ML beats the non-AI predictor and improves outcomes", "lower MAPE and ≥ carbon saving than gt_no_ml",
                    "Supported" if ok else "Not supported",
                    f"MAPE {ml:.1f} vs {tb:.1f} %; carbon {g.carbon_saving_pct:.1f} vs {n.carbon_saving_pct:.1f} %" if g is not None and n is not None else ""))
    # H5
    if e4 is not None and e5 is not None:
        gt = e4[e4.policy == "greenthread"].energy_saving_pct.values
        he = e4[e4.policy == "heuristic"].energy_saving_pct.values
        bat = e5[(e5.on_ac.astype(str) == "False")]
        mg = bat[bat.policy == "greenthread"].miss_rate.mean(); mh = bat[bat.policy == "heuristic"].miss_rate.mean()
        ok = (gt >= he - 0.5).all() and mg < mh
        out.append(("H5 on battery, GreenThread matches always-ECO and keeps deadlines it breaks",
                    "energy saving ≥ always-ECO − 0.5 pt at every SoC; fewer misses under tight deadlines",
                    "Supported (simulation)" if ok else "Not supported",
                    f"saving {gt.min():.1f}–{gt.max():.1f} vs {he.min():.1f}–{he.max():.1f} %; tight-deadline misses {100*mg:.2f} vs {100*mh:.2f} %"))
    # H6
    if led is not None:
        big = (led.tou_error_pct.abs() >= 5).mean()
        out.append(("H6 time-of-use accounting misstates battery carbon", "abs(error) ≥ 5 % in most trace × habit cells",
                    "Supported (simulation)" if big > 0.5 else "Not supported",
                    f"{100*big:.0f} % of cells; range {led.tou_error_pct.min():+.0f} to {led.tou_error_pct.max():+.0f} %"))
    # H7
    meas = None
    if td is not None and "energy_wh_measured" in td and td.energy_wh_measured.notna().sum() >= 10:
        d = td.dropna(subset=["energy_wh_measured"])
        piv = d.groupby(["kind", "units", "threads", "bg_threads", "mode"]).energy_wh_measured.median().unstack("mode")
        if {"ECO", "NORMAL"} <= set(piv.columns):
            meas = float((piv.ECO / piv.NORMAL).dropna().median())
    if meas is not None:
        out.append(("H7 ECO really saves energy on this laptop (measured)", "median measured ECO/NORMAL energy < 1",
                    "Confirmed" if meas < 1 else "Overturned", f"median ratio {meas:.3f} over paired configurations"))
    elif pm:
        out.append(("H7 ECO really saves energy on this laptop", "calibrated W/core ECO < normal",
                    "Confirmed (power model)" if pm["per_core_w_eco"] < pm["per_core_w_normal"] else "Overturned (power model)",
                    f"{pm['per_core_w_eco']:.2f} vs {pm['per_core_w_normal']:.2f} W/core ({pm.get('source')})"))
    else:
        out.append(("H7 ECO really saves energy on this laptop", "needs measured energy", "Not measured yet",
                    "run idle + calibrate + collect on battery (or with RAPL)"))
    return out


def write(cfg: Config, path: str | Path | None = None) -> Path:
    p = Path(path) if path else PACKAGE_ROOT / "docs" / "TEST_REPORT.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(build(cfg), encoding="utf-8")
    return p
